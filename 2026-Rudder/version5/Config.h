// ── 핀 매핑 ──────────────────────────────────────────────────────────────
// LED(74HC595)/부저는 현재 하드웨어 계획에 없어 미구현 (2026-07-22 결정)
// 상태 확인은 GCS 텔레메트리 + USB 시리얼 로그로 대체
#define PIN_SERVO        9
#define PIN_SD_CS       10
#define PIN_ARM_EN        7   // 서보 전원 MOSFET 게이트 제어 (LOW=차단, HIGH=통전)

// ── 통신 ─────────────────────────────────────────────────────────────────
#define BAUD_USB       115200
#define BAUD_TELEMETRY  57600

// ── 센서 I2C 주소 ─────────────────────────────────────────────────────────
#define IMU_ADDR        0x68   // MPU-6050/클론 (레지스터 직접제어, WHO_AM_I 무관)
#define BMP388_ADDR     0x76   // 실패 시 0x77 자동 재시도
#define INA219_ADDR     0x40

// ── 무효값 표시 ───────────────────────────────────────────────────────────
// BMP 실패 시 pressure/altitude_cm에 사용. -1은 정상적인 상대고도(-1cm 근처
// 노이즈)와 겹칠 수 있어서, 절대 정상값이 될 수 없는 INT32_MIN을 사용함.
#define ALT_INVALID     (-2147483647L - 1L)

// ── 서보 각도 ─────────────────────────────────────────────────────────────
#define SERVO_CLOSED_DEG    0
#define SERVO_EJECT_DEG    30   // 구조상 30도 초과 회전 불가 확인됨 (2026-07-27)
#define SERVO_RECMD_MS   1000   // 사출 후 목표각 재명령 주기 (회전 실패 대비 반복)

// ── 루프 주기 ─────────────────────────────────────────────────────────────
#define SENSOR_INTERVAL_MS   20    // 50 Hz 계측/로깅
#define TELEM_INTERVAL_MS   200    // 5 Hz 텔레메트리

// ── 발사 감지 (OR 조건: 둘 중 하나만 만족해도 발사 판정) ─────────────────
#define LAUNCH_ZACC_MG     2000    // 가속도 경로: Z축 2g 이상
#define LAUNCH_ZACC_MS      300    //              0.3초 연속 유지
#define LAUNCH_ALT_M       10.0f   // 고도 경로:   10m 이상
#define LAUNCH_ALT_COUNT      5    //              5회(0.1초) 연속
// 고도 단독 경로가 2m가 아니라 10m인 이유: 발사대 위 기압 노이즈/드리프트로
// 오탐하면 10초 타이머가 발사대에서 낙하산을 터뜨림. 10m는 발사 후 ~1초 내
// 도달하므로 감지 지연은 미미하면서 오탐은 확실히 차단.

// ── 주 사출 (비행 모드 진입 후에만 검사) ─────────────────────────────────
#define SAFE_LOCK_MS       3000    // 발사 감지 후 3초간 주 사출 검사 시작 안 함
#define MIN_APOGEE_ALT_M   30.0f   // 최고고도 30m 미만이면 정점 판단 안 함
#define APOGEE_DROP_M       3.0f   // 최고점 대비 3m 하강을
#define APOGEE_DROP_COUNT     5    // 5회(0.1초) 연속 확인 시 사출
#define PEAK_CONFIRM_COUNT    3    // 최고고도 갱신은 3회 연속 확인돼야 반영 (단일 스파이크 방지)

// ── 보조 사출 ─────────────────────────────────────────────────────────────
#define BACKUP_TIMER_MS   10000    // 발사 감지 후 10초 경과 시 무조건 사출

// ── 기준압 수집 ───────────────────────────────────────────────────────────
#define BASELINE_SAMPLES     50    // 준비(Armed) 진입 시 50샘플(약 1초) 평균
#define BASELINE_MIN_OK      45    // 이 이상 성공해야 "기준압 정상"으로 판단 (90%)

// ── 착륙 ─────────────────────────────────────────────────────────────────
// 자동판정 없음 — 회수 후 GCS에서 FORCE_LAND로 수동 전환 (2026-07-29 결정)

// ── SD 카드 ───────────────────────────────────────────────────────────────
#define FILE_PREALLOC_MB      8
#define SAMPLES_SYNC        100

// ── 시스템 상태 비트 (Packet.system_status) ──────────────────────────────
#define STATUS_BMP   0x01
#define STATUS_IMU   0x02
#define STATUS_SD    0x04
#define STATUS_INA   0x08
#define STATUS_BASELINE_BAD  0x10   // 기준압 수집 45/50 미달 (고도 신뢰 불가)

#endif
